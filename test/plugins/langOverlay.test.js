import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fixture } from '../helpers/contentFixtures.js';
import { scanPlugins, packIndexOf } from '../../server/plugins/registry.js';
import { readPackIndex, langMetaOf } from '../../shared/packs.js';
import { registerLangs, t, setLang, setMessages } from '../../shared/i18n.js';
import { loadUiMessages, dataChain } from '../../public/js/ui/lang.js';
import { createDataStore } from '../../public/js/data.js';
import { buildRecordOverlay } from '../../shared/i18nData.js';

test('one installed lang plugin overlays built-in UI and data, missing/invalid keys retain built-in strings', async tcase => {
  const { dir, put } = fixture(tcase);
  const ui = path.join(dir, 'public/i18n'); fs.mkdirSync(ui, { recursive: true });
  fs.writeFileSync(path.join(ui, 'qzz.json'), JSON.stringify({ _meta: { name: 'Base' }, 开始: 'Start', 返回: 'Back', '第 {n} 回合': 'Round {n}' }));
  const dataDir = path.join(dir, 'data'); fs.mkdirSync(path.join(dataDir, 'i18n'), { recursive: true });
  const source = { a: { name: '甲', desc: '说明' } };
  const overlay = (values) => ({ version: 1, lang: 'qzz', names: {}, files: { chess: { a: buildRecordOverlay(values) } } });
  const builtin = overlay([{ path: ['name'], zh: '甲', en: 'Alpha' }, { path: ['desc'], zh: '说明', en: 'Description' }]);
  fs.writeFileSync(path.join(dataDir, 'i18n/qzz.json'), JSON.stringify(builtin));
  const manifest = { class: 'lang', lang: 'qzz', scope: ['personal'], permissions: [], files: { ui: 'ui.json', data: 'game.json' } };
  put('first-overlay', manifest, { 'ui.json': { 开始: 'Begin', '第 {n} 回合': 'Broken' }, 'game.json': overlay([{ path: ['name'], zh: '甲', en: 'Overlay alpha' }]) });
  put('second-overlay', manifest, { 'ui.json': { 开始: 'Second' }, 'game.json': builtin });
  const scan = scanPlugins({ publicDir: path.join(dir, 'public'), dataDir, packsDir: path.join(dir, 'packs'), pluginsDir: path.join(dir, 'plugins') });
  assert.ok(scan.plugins.some(p => p.id === 'first-overlay'), JSON.stringify(scan.skipped));
  const second = scan.skipped.find(s => s.where === 'plugins/second-overlay/');
  assert.ok(second && second.issues.some(i => i.code === 'PLUGIN_DUPLICATE'));
  assert.match(second.problems.join('\n'), /first-overlay/);
  assert.match(second.problems.join('\n'), /one overlay per language/);
  assert.doesNotMatch(second.problems.join('\n'), /public\/i18n\/qzz\.json/);
  const entries = readPackIndex(packIndexOf(scan.plugins), 'lang');
  assert.equal(entries.length, 1);
  assert.equal(entries[0].files.ui, '/i18n/qzz.json');
  registerLangs(entries.map(langMetaOf));
  const fetch = async url => {
    const file = url.startsWith('/packs/') ? path.join(dir, 'plugins', url.slice(7)) : url.startsWith('/i18n/') ? path.join(dir, 'public', url) : path.join(dir, url);
    return { ok: fs.existsSync(file), json: async () => JSON.parse(fs.readFileSync(file, 'utf8')) };
  };
  assert.equal(await loadUiMessages('qzz', fetch), true);
  setLang('qzz');
  assert.equal(t('开始'), 'Begin'); assert.equal(t('返回'), 'Back'); assert.equal(t('第 {n} 回合', { n: 2 }), 'Round 2');
  const data = createDataStore({ fetch: async url => url === '/data/chess.json' ? { ok: true, json: async () => source } : fetch(url), retryDelays: [] });
  await data.load('chess'); await data.setLocale('qzz', dataChain('qzz'));
  assert.equal(data.get('chess').a.name, 'Overlay alpha');
  assert.equal(data.get('chess').a.desc, 'Description');
  assert.equal(data.getRaw('chess').a.name, '甲');
  setLang('zh'); setMessages('qzz', {});
});
