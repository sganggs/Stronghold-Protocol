// test/client-static.test.js — static and unit checks for the browser shell (public/).
//
// Static:
//   * shared/constants.js + shared/protocol.js import cleanly in Node (pure ESM, no Node APIs needed).
//   * every public/js/**/*.js file (and every inline <script type="module"> in public HTML) parses as an
//     ES module (`node --input-type=module --check`, stdin).
//   * public/index.html and public/dev/uikit.html only reference files that exist (src/href/import map);
//     /fonts/ and /assets/ are produced by the assets pipeline and are reported, not failed, when absent.
//   * the static import graph resolves: relative/absolute specifiers point at existing files (with browser
//     URL semantics: '../../shared/x.js' from /js/ is /shared/x.js), bare specifiers are in the import map,
//     and every named import is actually exported by its target.
// Unit (pure logic of the client modules, imported directly in Node — 'preact'/'htm' resolve from
// node_modules): store, net (fake WebSocket + fake timers), identity (fake BroadcastChannel hub), data,
// screen helpers, toasts.

