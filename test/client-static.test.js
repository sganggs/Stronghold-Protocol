function walk(dir, ext, out = []) {
  for (const name of readdirSync(dir)) {
    const p = path.join(dir, name);
    if (statSync(p).isDirectory()) walk(p, ext, out);
    else if (p.endsWith(ext)) out.push(p);
  }
  return out;
}

/** URL path served by the server → file on disk (mirrors the server/http/static.js mounts). */
function urlPathToFile(urlPath) {
  const clean = decodeURIComponent(urlPath.split(/[?#]/)[0]);
  if (clean.startsWith('/shared/')) return path.join(ROOT, clean);
  if (clean.startsWith('/data/')) return path.join(ROOT, clean);
  return path.join(PUBLIC, clean);
}

/** File under public/ → its URL path. */
const fileToUrlPath = (file) => '/' + path.relative(PUBLIC, file).split(path.sep).join('/');

function checkModuleSyntax(source) {
  const r = spawnSync(process.execPath, ['--input-type=module', '--check'], { input: source, encoding: 'utf8' });
  return r.status === 0 ? null : (r.stderr || r.stdout || 'syntax error').split('\n').slice(0, 6).join('\n');
}

function parseImportMap(htmlSrc) {
  const m = htmlSrc.match(/<script\s+type="importmap"\s*>([\s\S]*?)<\/script>/);
  return m ? JSON.parse(m[1]).imports || {} : {};
}

function inlineModules(htmlSrc) {
  const out = [];
  const re = /<script\s+type="module"\s*>([\s\S]*?)<\/script>/g;
  let m;
  while ((m = re.exec(htmlSrc))) out.push(m[1]);
  return out;
}

function htmlRefs(htmlSrc) {
  const refs = [];
  const re = /\s(?:src|href)="([^"]+)"/g;
  let m;
  while ((m = re.exec(htmlSrc))) {
    const v = m[1];
    if (/^(https?:|data:|mailto:|#|javascript:)/.test(v)) continue;
    refs.push(v);
  }
  return refs;
}

/** Static import/export-from statements: [{ spec, clause }]. Statements start at the beginning of a line. */
function staticImports(src) {
  const out = [];
  const re = /^[ \t]*(?:import|export)\b([^;'"]*?)\bfrom\s*['"]([^'"]+)['"]|^[ \t]*import\s*['"]([^'"]+)['"]/gm;
  let m;
  while ((m = re.exec(src))) {
    if (m[3]) out.push({ spec: m[3], clause: '' });
    else out.push({ spec: m[2], clause: m[1].trim() });
  }
  return out;
}

/** Names a module exports ('*' when it re-exports everything and names can't be listed). */
function exportedNames(src) {
  const names = new Set();
  let m;
  const decl = /export\s+(?:async\s+)?(?:function\s*\*?|const|let|var|class)\s+([\w$]+)/g;
  while ((m = decl.exec(src))) names.add(m[1]);
  const list = /export\s*\{([^}]*)\}/g;
  while ((m = list.exec(src))) {
    for (const part of m[1].split(',')) {
      const p = part.trim();
      if (!p) continue;
      const as = p.split(/\s+as\s+/);
      names.add((as[1] || as[0]).trim());
    }
  }
  if (/export\s+default\b/.test(src)) names.add('default');
  if (/export\s*\*\s*from/.test(src)) names.add('*');
  return names;
}

/** Imported binding names from an import clause ('default' for a default import). */
function importedNames(clause) {
  if (!clause || /^\*\s*as\s/.test(clause)) return [];
  const names = [];
  const brace = clause.match(/\{([^}]*)\}/);
  if (brace) {
    for (const part of brace[1].split(',')) {
      const p = part.trim();
      if (p) names.push(p.split(/\s+as\s+/)[0].trim());
    }
  }
  const head = clause.replace(/\{[^}]*\}/, '').replace(/,/g, ' ').trim();
  if (head && !head.startsWith('*') && /^[\w$]+$/.test(head)) names.push('default');
  return names;
}

