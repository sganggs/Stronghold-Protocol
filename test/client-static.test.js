function fakeFetch(files) {
  const calls = [];
  const fn = async (url) => {
    calls.push(url);
    const name = url.split('/').pop();
    if (!(name in files)) return { ok: false, status: 404, json: async () => ({}) };
    const v = files[name];
    return { ok: true, status: 200, json: async () => (typeof v === 'string' ? JSON.parse(v) : v) };
  };
  fn.calls = calls;
  return fn;
}

