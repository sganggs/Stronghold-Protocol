function fakeTimers(start = 1_000_000) {
  let now = start;
  let seq = 0;
  const q = new Map();
  const add = (fn, ms, every) => { const id = ++seq; q.set(id, { at: now + Math.max(0, ms | 0), fn, every }); return id; };
  return {
    now: () => now,
    setTimeout: (fn, ms) => add(fn, ms, 0),
    clearTimeout: (id) => q.delete(id),
    setInterval: (fn, ms) => add(fn, ms, Math.max(1, ms | 0)),
    clearInterval: (id) => q.delete(id),
    advance(ms) {
      const end = now + ms;
      for (;;) {
        let next = null;
        for (const [id, t] of q) if (t.at <= end && (!next || t.at < next[1].at)) next = [id, t];
        if (!next) break;
        const [id, t] = next;
        now = t.at;
        if (t.every) t.at += t.every; else q.delete(id);
        t.fn();
      }
      now = end;
    },
  };
}

function makeFakeWS() {
  const sockets = [];
  class FakeWS {
    constructor(url) {
      this.url = url;
      this.readyState = 0;
      this.sent = [];
      this.closedWith = null;
      sockets.push(this);
    }
    send(data) {
      if (this.readyState !== 1) throw new Error('not open');
      this.sent.push(JSON.parse(data));
    }
    close(code) { this.readyState = 3; this.closedWith = code ?? 1000; }
    // test helpers
    open() { this.readyState = 1; this.onopen?.(); }
    recv(obj) { this.onmessage?.({ data: typeof obj === 'string' ? obj : JSON.stringify(obj) }); }
    drop(code = 1006) { this.readyState = 3; this.onclose?.({ code }); }
    last(t) { return [...this.sent].reverse().find((m) => m.t === t); }
  }
  return { FakeWS, sockets };
}

async function makeNet(extra = {}) {
  const { Net } = await mod('net.js');
  const timers = fakeTimers();
  const { FakeWS, sockets } = makeFakeWS();
  const net = new Net({ url: 'ws://test/ws', WebSocket: FakeWS, timers, now: timers.now, random: () => 0.5, getToken: () => 'tok-1', ...extra });
  const statuses = [];
  net.on('status', (s) => statuses.push(s.status));
  return { net, timers, sockets, statuses, ws: () => sockets[sockets.length - 1] };
}

/** Connect, open, set a name and complete the handshake. */
async function onlineNet(extra) {
  const ctx = await makeNet(extra);
  ctx.net.setName('凯尔希');
  ctx.ws().open();
  const hello = ctx.ws().last('hello');
  ctx.ws().recv({ t: 'welcome', rid: hello.rid, playerId: 'p_1', token: 'tok-2', name: '凯尔希', serverNow: ctx.timers.now() });
  return ctx;
}

const quiet = async (fn) => {
  const w = console.warn;
  console.warn = () => {};
  try { return await fn(); } finally { console.warn = w; }
};

/** Answer the latest ping on a fake socket. */
function ws0Pong(sock) {
  const p = sock.last('ping');
  if (p) sock.recv({ t: 'pong', c: p.c, s: p.c });
}

