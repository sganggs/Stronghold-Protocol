describe('static import graph resolves', () => {
  const importMap = parseImportMap(readFileSync(path.join(PUBLIC, 'index.html'), 'utf8'));
  const exportsCache = new Map();
  const exportsOf = (file) => {
    if (!exportsCache.has(file)) exportsCache.set(file, exportedNames(readFileSync(file, 'utf8')));
    return exportsCache.get(file);
  };

  function checkSource(label, src, baseUrl) {
    for (const { spec, clause } of staticImports(src)) {
      let urlPath;
      if (/^(\.{1,2}\/|\/)/.test(spec)) urlPath = new URL(spec, baseUrl).pathname;
      else {
        assert.ok(importMap[spec], `${label}: bare specifier '${spec}' is not in the import map`);
        urlPath = importMap[spec];
      }
      const file = urlPathToFile(urlPath);
      assert.ok(existsSync(file), `${label}: '${spec}' → ${urlPath} does not exist`);
      const names = exportsOf(file);
      if (names.has('*')) continue;
      for (const n of importedNames(clause)) {
        assert.ok(names.has(n), `${label}: '${n}' is not exported by ${urlPath}`);
      }
    }
  }

  for (const file of JS_FILES) {
    test(path.relative(ROOT, file), () => {
      checkSource(path.relative(ROOT, file), readFileSync(file, 'utf8'), new URL(`http://host${fileToUrlPath(file)}`));
    });
  }
  test('dev/uikit.html inline module', () => {
    const src = readFileSync(path.join(PUBLIC, 'dev/uikit.html'), 'utf8');
    for (const mod of inlineModules(src)) checkSource('uikit.html', mod, new URL('http://host/dev/uikit.html'));
  });
  test('client modules never import Node built-ins', () => {
    for (const file of JS_FILES) {
      const src = readFileSync(file, 'utf8');
      assert.doesNotMatch(src, /from\s+['"]node:/, `${path.relative(ROOT, file)} imports a node: module`);
    }
  });
});

