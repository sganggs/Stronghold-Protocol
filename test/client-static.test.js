function memStorage() {
  const m = new Map();
  return {
    getItem: (k) => (m.has(k) ? m.get(k) : null),
    setItem: (k, v) => { m.set(k, String(v)); },
    removeItem: (k) => { m.delete(k); },
    /** sessionStorage is copied when a tab is duplicated */
    clone() { const c = memStorage(); for (const [k, v] of m) c.setItem(k, v); return c; },
  };
}

/** In-memory BroadcastChannel hub: messages reach every other open member asynchronously. */
function channelHub() {
  const members = new Set();
  return {
    create() {
      const ch = {
        listeners: new Set(),
        postMessage(data) {
          if (!members.has(ch)) throw new Error('InvalidStateError: channel closed');
          const copy = structuredClone(data);
          for (const m of members) {
            if (m === ch) continue;
            queueMicrotask(() => { if (members.has(m)) for (const fn of m.listeners) fn({ data: copy }); });
          }
        },
        addEventListener(type, fn) { if (type === 'message') ch.listeners.add(fn); },
        close() { members.delete(ch); },
      };
      members.add(ch);
      return ch;
    },
  };
}

