// Compile confirmed owner demonstrations into role/tile frequencies. Example 6 is held out on every map.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { validateAnnotation } from './model.mjs';

const root = new URL('../../', import.meta.url);
const evidencePath = new URL('docs/research/layout-demonstrations.json', root);
let evidence;
// Default: reproducibly compile the checked-in evidence, without the owner's ignored local files.
// --storage <directory>: explicitly import newly confirmed demonstrations, preserving the original saves.
if (process.argv.includes('--storage')) {
  const arg = process.argv[process.argv.indexOf('--storage') + 1];
  if (!arg) throw new Error('--storage needs a directory');
  const storage = pathToFileURL(resolve(arg) + '/');
  const corpus = JSON.parse(readFileSync(new URL('examples.json', storage), 'utf8'));
  const saved = JSON.parse(readFileSync(new URL('annotations.json', storage), 'utf8'));
  if (saved.fingerprint !== corpus.fingerprint) throw new Error('Corpus fingerprint mismatch');
  const examples = [];
  for (const c of corpus.cases) {
    const a = saved.annotations[c.id];
    if (!a?.confirmed) continue;
    validateAnnotation(corpus, c.id, a);
    const units = a.placements.map(p => {
      const u = c.units.find(u => u.uid === p.uid);
      return { role: u.role, place: u.place, block: u.block, range: u.range, row: p.row, col: p.col, dir: p.dir };
    });
    examples.push({ id: c.id, mapId: c.mapId, heldOut: c.example === 6, notes: a.notes, units });
  }
  evidence = { schema: 1, fingerprint: corpus.fingerprint, scope: 'ordinary rounds 1-13 only', examples };
  writeFileSync(evidencePath, JSON.stringify(evidence) + '\n');
} else evidence = JSON.parse(readFileSync(evidencePath, 'utf8'));

const profiles = {};
for (const c of evidence.examples) {
  if (c.heldOut) continue;
  const profile = profiles[c.mapId] ||= {};
  for (const u of c.units) {
    const role = u.role === 'block' && !u.range.some(([r, c]) => r === 0 && c === 0) ? 'support' : u.role;
    const cells = profile[role] ||= {};
    const key = `${u.row},${u.col}`;
    cells[key] = (cells[key] || 0) + 1;
  }
}
const lines = Object.entries(profiles).map(([id, roles]) => `  ${JSON.stringify(id)}: ${JSON.stringify(roles)},`);
writeFileSync(new URL('server/match/botFormationProfiles.js', root),
  '// Generated by tools/layout-lab/learn.mjs from confirmed owner layouts (2026-10-15).\n' +
  '// Five examples/map train these role frequencies; example 6 is reserved for validation.\n' +
  '// No operator identities, directions or boss layouts are encoded.\n' +
  `export const FORMATION_PROFILES = Object.freeze({\n${lines.join('\n')}\n});\n`);
console.log(`Compiled ${evidence.examples.length} confirmed examples, ${Object.keys(profiles).length} map profiles.`);
