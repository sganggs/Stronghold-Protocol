// shared/plugins/surface.js — the frozen plugin API v1 as data (DESIGN §32.13, docs/PLUGIN-API.md). No Node builtin
// and no import of server/: the browser, the CLI and the test share it. Closed sets live in the modules that own
// them. The DSL vocabulary and the studio routes are passed in (`buildSurface({ dsl, studioRoutes })`) because those
// modules are server-side; this file does not load them.
//
// A row: { name, group, stability, since, anchor }. stability is stable, experimental or internal. A stable name is
// not removed or renamed while PLUGIN_API.min still covers the level that published it. Experimental may change.
// Internal is not for plugin authors. `since` is the release that froze that row (0.3.0, not the dev build); it is
// per row, so a later release sets only its own new rows to its own version (`SURFACE_SINCE_NEXT`) and the rows frozen
// earlier keep theirs — the test's baseline of stable names is never rewritten by an unrelated release.
//
// [ASSUMED] script / trusted classes and the permissions only they use (sim.code, meta.code, mode.code, trusted.page,
// trusted.server) are experimental. sp:sdk@1 (P3a) is experimental: its members (SDK_MEMBERS) and the module's exports (SDK_EXPORTS). Studio
// routes are stable and local-only; the local-only rule is prose in PLUGIN-API.md, not a fourth stability. STAT_NAMES
// is part of the frozen DSL vocabulary. Overlay names are derived by walking ASSET_CONTAINERS (a free-keyed container
// is `….*`; audio.bgm's tracks are named). Record names are the top-level properties of RECORD_SCHEMA's two forms.

