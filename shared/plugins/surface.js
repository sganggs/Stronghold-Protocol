/** The exports of shared/plugins/sdk.js besides SDK_ID / SDK_MEMBERS (test/plugins/surface.test.js checks the real module has no other). */
export const SDK_EXPORTS = Object.freeze(['constants', 'createSDK', 'dir', 'kit', 'math', 'targeting']);

/** The release that froze this surface (the first one; 0.3.0 published plugin API v1). Dev builds of that release count as it. */
export const SURFACE_SINCE = '0.3.0';
/**
 * The release a name added after that freeze is published in. `add` defaults to `SURFACE_SINCE`, so every row frozen
 * with the first surface keeps 0.3.0, and a later release passes this for the rows it adds instead of rewriting the
 * whole table. It follows `PLUGIN_API` — the level is what actually makes a new name unusable on an older build
 * (docs/PLUGIN-API.md "Version policy") — so while `current` still equals `min` the next release is this one, and a
 * dev build of a release counts as that release rather than as the dev build.
 */
export const SURFACE_SINCE_NEXT = PLUGIN_API.current > PLUGIN_API.min ? APP_VERSION.replace(/-dev$/, '') : SURFACE_SINCE;

export const SURFACE_MARKERS = Object.freeze({
  start: '<!-- plugin-surface:start (generated by node tools/plugin.mjs surface --write) -->',
  end: '<!-- plugin-surface:end -->',
});

/** Permissions that only an unsupported class may hold. Experimental until that class is supported. */
const EXPERIMENTAL_PERMISSIONS = new Set(['sim.code', 'meta.code', 'mode.code', 'trusted.page', 'trusted.server']);
/** Code plugins (P3a trusted, P3b sandbox) are new in 0.3.0: their classes and their manifest field stay experimental. */
const EXPERIMENTAL_CLASSES = new Set(['script', 'trusted']);
const EXPERIMENTAL_FIELDS = new Set(['overrides']);

const DSL_GROUPS = Object.freeze([
  ['trigger', 'TRIGGERS'],
  ['condition', 'CONDITIONS'],
  ['action', 'ACTIONS'],
  ['target', 'TARGETS'],
  ['metaTrigger', 'META_TRIGGERS'],
  ['metaAction', 'META_ACTIONS'],
  ['value', 'VALUE_OPS'],
  ['skillKind', 'SKILL_KINDS'],
  ['stat', 'STAT_NAMES'],
]);

/**
 * Overlay names from ASSET_CONTAINERS. A string kind is one leaf. `fields` is walked. `each` is `prefix.*`.
 * A container with `keys` names those keys. Any other free-keyed container (the record itself is one image, or `each`)
 * is `overlay.<path>.*`.
 * @param {readonly { path: string[], record: any, keys?: readonly string[] }[]} [containers]
 * @returns {string[]}
 */
export function overlayNames(containers = ASSET_CONTAINERS) {
  /** @type {string[]} */
  const out = [];
  const walk = (kind, prefix) => {
    if (typeof kind === 'string') { out.push(prefix); return; }
    if (kind && kind.fields) {
      for (const [k, v] of Object.entries(kind.fields)) walk(v, `${prefix}.${k}`);
      return;
    }
    if (kind && kind.each) { out.push(`${prefix}.*`); return; }
    throw new Error(`unknown asset kind at ${prefix}`);
  };
  for (const c of containers) {
    const base = `overlay.${c.path.join('.')}`;
    if (Array.isArray(c.keys)) for (const k of c.keys) walk(c.record, `${base}.${k}`);
    else if (typeof c.record === 'string' || (c.record && c.record.each)) out.push(`${base}.*`);
    else walk(c.record, base);
  }
  return out;
}

/**
 * Top-level compact-record fields. `skillSpec` stays inside `skills`; it is not expanded.
 * @param {{ anyOf?: { properties?: Record<string, unknown> }[] }} [schema]
 * @returns {{ operator: string[], generic: string[] }}
 */
export function recordNames(schema = RECORD_SCHEMA) {
  const [operator, generic] = schema.anyOf || [];
  return {
    operator: Object.keys(operator?.properties || {}),
    generic: Object.keys(generic?.properties || {}),
  };
}

/**
 * @param {{ dsl?: Record<string, readonly string[]>, studioRoutes?: readonly string[] }} [extra]
 * @returns {{ name: string, group: string, stability: 'stable' | 'experimental' | 'internal', since: string, anchor: string }[]}
 */
export function buildSurface(extra = {}) {
  /** @type {{ name: string, group: string, stability: 'stable' | 'experimental' | 'internal', since: string, anchor: string }[]} */
  const rows = [];
  const added031 = new Set(['record.operator.origin', 'error.PLUGIN_BOSS_CENTRE_DEPLOYABLE', 'sdk.sp:sdk@1.dir', 'sdk.sp:sdk@1.targeting', 'sdk.export.dir', 'sdk.export.targeting',
    'manifest.field.offers', 'permission.offers', 'error.PLUGIN_OFFER_SHAPE', 'error.PLUGIN_OFFER_ROUNDS', 'error.PLUGIN_OFFER_REFERENCE',
    'error.PLUGIN_RECORD_HIDDEN', 'error.PLUGIN_RECORD_PAIR', 'error.PLUGIN_RECORD_ART', 'error.PLUGIN_RECORD_ORIGIN',
    'error.PLUGIN_FORGE_MOUNT', 'error.PLUGIN_FORGE_PANEL_SCRIPT', 'error.PLUGIN_UI_SLOT_SHARED', 'error.PLUGIN_STUDIO_CONSOLE_SCENARIO',
    'ui.message.host.result', 'ui.message.host.net',
    'manifest.field.notices', 'error.PLUGIN_THEME_NAME', 'error.PLUGIN_THEME_VALUE', 'error.PLUGIN_THEME_LIMIT', 'error.PLUGIN_THEME_SHAPE',
    'error.PLUGIN_NOTICE_SHAPE', 'error.PLUGIN_NOTICE_LIMIT', 'error.PLUGIN_NOTICE_TEXT', 'error.PLUGIN_NOTICE_LANG',
    'studio.route.POST /studio/api/console/options', 'studio.route.POST /studio/api/console/build',
    'manifest.field.rules', 'error.PLUGIN_RULE_CONFLICT', 'error.PLUGIN_RULES', ...RULE_NAMES.map((name) => `rule.${name}`)]);
  const add = (name, group, stability, anchor, since) => rows.push({ name, group, stability, since: since ?? (added031.has(name) ? '0.3.1' : SURFACE_SINCE), anchor });
  for (const field of MANIFEST_FIELDS) add(`manifest.field.${field}`, 'manifest', EXPERIMENTAL_FIELDS.has(field) ? 'experimental' : 'stable', 'shared/plugins/manifest.js#MANIFEST_FIELDS');
  for (const name of RULE_NAMES) add(`rule.${name}`, 'rule', 'stable', 'shared/plugins/rules.js#RULE_SWITCHES');
  for (const name of Object.keys(PERMISSIONS)) add(`permission.${name}`, 'permission', EXPERIMENTAL_PERMISSIONS.has(name) ? 'experimental' : 'stable', 'shared/plugins/manifest.js#PERMISSIONS');
  for (const [name, cls] of Object.entries(PLUGIN_CLASSES)) add(`class.${name}`, 'class', cls.status === 'unsupported' || EXPERIMENTAL_CLASSES.has(name) ? 'experimental' : 'stable', 'shared/plugins/manifest.js#PLUGIN_CLASSES');
  for (const op of PATCH_OPS) add(`patch.op.${op}`, 'patch', 'stable', 'shared/plugins/patch.js#PATCH_OPS');
  const records = recordNames();
  for (const name of records.operator) add(`record.operator.${name}`, 'record', 'stable', 'shared/plugins/recordsSchema.js#RECORD_SCHEMA');
  for (const name of records.generic) add(`record.generic.${name}`, 'record', 'stable', 'shared/plugins/recordsSchema.js#RECORD_SCHEMA');
  for (const name of overlayNames()) add(name, 'overlay', 'stable', 'shared/plugins/visual.js#ASSET_CONTAINERS');
  const dsl = extra.dsl || {};
  for (const [group, key] of DSL_GROUPS) for (const name of dsl[key] || []) add(`dsl.${group}.${name}`, 'dsl', 'stable', `server/sim/content/dsl/vocab.js#${key}`);
  for (const name of UI_PLUGIN_MESSAGES) add(`ui.message.plugin.${name}`, 'ui', 'stable', 'shared/plugins/ui.js#UI_PLUGIN_MESSAGES');
  for (const name of UI_HOST_MESSAGES) add(`ui.message.host.${name}`, 'ui', 'stable', 'shared/plugins/ui.js#UI_HOST_MESSAGES');
  for (const name of UI_SLOT_IDS) add(`ui.slot.${name}`, 'ui', 'stable', 'shared/plugins/manifest.js#UI_SLOT_IDS');
  for (const route of extra.studioRoutes || []) add(`studio.route.${route}`, 'studio', 'stable', 'server/studio/index.js#STUDIO_ROUTES');
  for (const code of Object.keys(PLUGIN_ERRORS)) add(`error.${code}`, 'error', 'stable', 'shared/plugins/errors.js#PLUGIN_ERRORS');
  for (const name of CATALOG_FIELDS) add(`catalog.field.${name}`, 'catalog', 'stable', 'shared/plugins/catalog.js#CATALOG_FIELDS');
  for (const name of CATALOG_ENTRY_FIELDS) add(`catalog.entry.${name}`, 'catalog', 'stable', 'shared/plugins/catalog.js#CATALOG_ENTRY_FIELDS');
  add(`sdk.${SDK_ID}`, 'sdk', 'experimental', 'shared/plugins/sdk.js#SDK_ID');
  add('sdk.SDK_MEMBERS', 'sdk', 'internal', 'shared/plugins/sdk.js#SDK_MEMBERS');
  for (const name of SDK_MEMBERS) add(`sdk.${SDK_ID}.${name}`, 'sdk', 'experimental', 'shared/plugins/sdk.js#SDK_MEMBERS');
  // the module's own exports (P3a): the facade's pieces a host builds `sp` from — experimental in 0.3.0
  for (const name of SDK_EXPORTS) add(`sdk.export.${name}`, 'sdk', 'experimental', `shared/plugins/sdk.js#${name}`);
  add('api.PLUGIN_API.min', 'api', 'stable', 'shared/constants.js#PLUGIN_API');
  add('api.PLUGIN_API.current', 'api', 'stable', 'shared/constants.js#PLUGIN_API');
  return rows;
}

/**
 * The markdown table of `rows` (name, stability, since, anchor).
 * @param {ReturnType<typeof buildSurface>} rows
 */
export function surfaceMarkdown(rows) {
  const head = '| name | stability | since | anchor |\n| --- | --- | --- | --- |';
  const body = rows.map((r) => `| \`${r.name}\` | ${r.stability} | ${r.since} | \`${r.anchor}\` |`).join('\n');
  return `${head}\n${body}`;
}

/**
 * Export names of `namespace` (the module object of shared/plugins/sdk.js, or a stand-in) that have no row anchored
 * at `shared/plugins/sdk.js#<export>`. A new export fails until a row names it. Members listed inside SDK_MEMBERS are
 * not exports of the module; the export `SDK_MEMBERS` itself is.
 * @param {Record<string, unknown>} namespace
 * @param {{ anchor: string }[]} rows
 * @returns {string[]}
 */
export function uncoveredSdkExports(namespace, rows) {
  const anchors = new Set(rows.map((r) => r.anchor));
  return Object.keys(namespace).filter((name) => !anchors.has(`shared/plugins/sdk.js#${name}`)).sort();
}

