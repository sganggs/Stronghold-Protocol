/**
 * One path per colour: every row's runs of a character as 1-high rectangles.
 * @param {string[]} rows @param {string} ch
 */
export function pixPath(rows, ch) {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      if (row[x] !== ch) { x++; continue; }
      let w = 1;
      while (row[x + w] === ch) w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return d;
}

/**
 * A pixel glyph from PIX (inline SVG, crisp edges, sized by CSS; the colour is the element's `color`).
 * @param {{ kind: keyof typeof PIX, class?: string, style?: string }} props
 */
export function PixBot({ kind, class: cls, style = null }) {
  const rows = PIX[kind] || PIX.bot;
  const w = rows[0].length;
  return h('svg', { class: cx('pix', `pix--${kind}`, cls), style, viewBox: `0 0 ${w} ${rows.length}`, 'shape-rendering': 'crispEdges', 'aria-hidden': 'true' },
    h('path', { class: 'pix__a', d: pixPath(rows, '#') }),
    h('path', { class: 'pix__b', d: pixPath(rows, '+') }));
}
